from datetime import datetime
from fastapi import APIRouter,Depends,HTTPException
from sqlalchemy.orm import Session
from app.database import get_db
from app.schemas.localized import *
from app.services import localized_data_service as s
router=APIRouter(tags=["localized-business-data"])
def call(fn,*a,**kw):
    try:return fn(*a,**kw)
    except LookupError as e:raise HTTPException(404,str(e))
    except ValueError as e:raise HTTPException(400,str(e))
@router.post("/sites",response_model=SiteRead,status_code=201)
def create_site(x:SiteCreate,db:Session=Depends(get_db)):return call(s.create_site,db,x)
