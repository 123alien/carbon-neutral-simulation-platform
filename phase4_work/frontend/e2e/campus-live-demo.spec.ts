import {test,expect} from '@playwright/test';
test('校园实时仿真大屏由后端快照驱动且定时更新',async({page,request})=>{
 const sites=await (await request.get('http://127.0.0.1:8000/api/sites')).json();
 const site=sites.find((x:{code:string})=>x.code==='HBUE');expect(site).toBeTruthy();
 const response=await request.get(`http://127.0.0.1:8000/api/result-interface/campuses/${site.id}/live-demo`);
 expect(response.ok()).toBeTruthy();const data=await response.json();
 expect(data.buildings).toHaveLength(16);expect(data.hourly).toHaveLength(168);
 expect(Math.abs(data.current.balance_error_kwh)).toBeLessThan(1e-8);
 expect(Math.abs(data.buildings.reduce((sum:number,b:{emission_t:number})=>sum+b.emission_t,0)-data.total_emission_t)).toBeLessThan(1e-6);
 await page.setViewportSize({width:1920,height:1080});await page.goto(`/3d?site=${site.id}`);
 const notice=page.getByTestId('campus-live-notice');await expect(notice).toBeVisible();
 await expect(notice).toContainText('示范仿真数据');
 await expect(page.locator('.left-top')).not.toContainText('暂无数据');
 await expect(page.locator('.left-bottom')).not.toContainText('暂无图表数据');
 const monitor=page.getByTestId('device-monitor-scroll');
 await expect(monitor.locator('button')).toHaveCount(68);
 await page.mouse.move(0,0);
 await expect.poll(()=>monitor.evaluate(el=>el.scrollTop)).toBeGreaterThan(0);
 await page.getByRole('button',{name:'暂停滚动',exact:true}).click();
 const stopped=await monitor.evaluate(el=>el.scrollTop);
 await page.waitForTimeout(250);
 expect(await monitor.evaluate(el=>el.scrollTop)).toBe(stopped);
 await page.getByRole('button',{name:'继续滚动',exact:true}).click();
 const initial=await notice.textContent();
 await expect.poll(()=>notice.textContent(),{timeout:20000}).not.toBe(initial);
 await page.screenshot({path:'../qa_report/hbue-campus-live-dashboard.png'});
 const building=data.buildings.find((b:{building_id:string})=>b.building_id==='HBUE-B042');
 await page.goto(`/carbon?site=${site.id}&building=${building.id}&at=${encodeURIComponent(data.timestamp)}`);
 const accounting=page.getByTestId('campus-snapshot-accounting');
 await expect(accounting).toBeVisible();await expect(accounting).toContainText('与校园大屏共用同一核算快照');
 await expect(accounting).toContainText(`核算对象：${building.name}`);
 await expect(accounting).toContainText(building.emission_t.toLocaleString('zh-CN',{maximumFractionDigits:2}));
 await page.screenshot({path:'../qa_report/hbue-building-shared-accounting.png'});
 await page.goto(`/recommendations?site=${site.id}`);
 await expect(page.getByText('当前平均负荷',{exact:true})).toBeVisible();
 const baseline=page.locator('.baseline-grid > div').filter({hasText:'当前平均负荷'});
 await expect(baseline).not.toContainText('暂无数据 / 无法评估',{timeout:5000});
});
