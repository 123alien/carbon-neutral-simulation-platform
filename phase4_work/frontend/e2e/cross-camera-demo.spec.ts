import {test,expect} from '@playwright/test';
import demo from './fixtures/cross-camera-demo.json' with {type:'json'};

test('跨镜示范路径多选、详情和能碳叠加',async({page})=>{
 await page.setViewportSize({width:1920,height:1080});
 const site={id:15,enterprise_id:15,code:'HBUE',name:'湖北经济学院智慧低碳校园',timezone:'Asia/Shanghai',status:'ACTIVE',metadata_json:{campus_id:'HBUE'}};
 await page.route('**/api/**',r=>{const path=new URL(r.request().url()).pathname;
 if(!path.startsWith('/api/'))return r.continue();
 if(path==='/api/sites')return r.fulfill({json:[site]});
 if(path.endsWith('/overview'))return r.fulfill({json:{site,anomaly_count:0,data_completeness_rate:1}});
 if(path.endsWith('/carbon'))return r.fulfill({json:{total_emission_t:null,trend:[]}});
 if(path.endsWith('/paths'))return r.fulfill({json:demo});
 return r.fulfill({json:[]});});
 await page.goto('/3d');
 await page.locator('.layer-control .reserved input').check();
 const panel=page.getByTestId('trajectory-panel');
 await expect(panel).toContainText('当前匿名编号 25');
 await expect(page.locator('.leaflet-overlay-pane path')).not.toHaveCount(0);
 const retained=await page.locator('.demo-activity-flow').first().elementHandle();
 await panel.getByLabel('教学区活动 5',{exact:true}).uncheck();
 await expect(panel).toContainText('当前匿名编号 20');
 expect(await retained!.evaluate(node=>node.isConnected)).toBe(true);
 await panel.getByLabel('体育活动 5',{exact:true}).uncheck();
 await expect(panel).toContainText('当前匿名编号 15');
 await panel.getByLabel('体育活动 5',{exact:true}).check();
 await expect(panel).toContainText('当前匿名编号 20');
 await panel.getByLabel('教学区活动 5',{exact:true}).check();
 await expect(panel).toContainText('当前匿名编号 25');
 await panel.getByRole('button',{name:'全部隐藏',exact:true}).click();
 await expect(panel).toContainText('当前匿名编号 0');
 await expect(page.locator('.demo-activity-flow')).toHaveCount(0);
 await panel.getByRole('button',{name:'全部显示',exact:true}).click();
 await expect(panel).toContainText('当前匿名编号 25');
 await page.screenshot({path:'../qa_report/hbue-multi-activity-paths.png'});
 await panel.getByPlaceholder('匿名编号').fill('G001');
 await expect(panel).toContainText('当前匿名编号 1');
 await panel.locator('.path-list button').first().click();
 await expect(panel.locator('.trajectory-detail')).toContainText('G001');
 await expect(panel.locator('.trajectory-detail')).toContainText('CAM05 → CAM06 → CAM01');
 await page.getByRole('button',{name:'综合能耗',exact:true}).click();
 await expect(page.getByLabel('能耗热力',{exact:true})).toBeChecked();
 await expect(panel).toBeVisible();
 await page.screenshot({path:'../qa_report/hbue-cross-camera-demo.png'});
});
